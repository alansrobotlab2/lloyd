# ── clause 3, half one: what the probe can reach ───────────────────────────
#
# The first version of this walker set `root = path.parent` — `eval/` — so every
# `app.*` target resolved to `eval/app/*.py`, matched no file, and the walk
# returned the probe alone. Both "no forbidden module" assertions were then
# asserting an empty closure: reachable-by-construction, unfailable by content.
# The walker below is rooted at the repo root, records BOTH forms of every
# import, and returns the file set as well as the names so a test can prove the
# closure is not empty instead of trusting that it is.

#: Modules that own or carry an inference request on this box. The four
#: first-party ones are the ones with a POST in them; the rest are the transports
#: a request would travel on.
FORBIDDEN_MODULES = ("app.harness.client", "app.engine_client",
                     "app.compaction_llm", "app.harness.mcp_pool",
                     "openai", "httpx", "requests")

#: What the runtime guard refuses to LOAD. Only the four first-party modules that
#: own an inference request, deliberately not the transport libraries below: the
#: component rebuild clause 3 itself requires runs `build_system_prompt`, which
#: imports `agent_mcp.skills` -> `mcp.types`, and `mcp` pulls its own HTTP client
#: library in at import time. Forbidding that import would forbid the rebuild, so
#: the runtime claim is carried by the EVENTS: a transport library sitting in
#: `sys.modules` sent nothing, a `socket.connect` did. The transport libraries
#: stay forbidden to the probe's own import statements, which the static closure
#: and `test_the_probe_imports_no_engine_module_itself` both check.
RUNTIME_FORBIDDEN_IMPORTS = ("openai", "app.compaction_llm")

#: Audit events that mean "a request left the process" or "another process did
#: the probe's work". No probe path needs any of them.
FORBIDDEN_EVENTS = ("socket.connect", "socket.connect_ex", "socket.getaddrinfo",
                    "socket.create_connection", "socket.sendto",
                    "http.client.connect", "urllib.Request", "subprocess.Popen")


def _imports_of(tree, module_level_only: bool) -> "list[tuple[int, str | None, str]]":
    """(level, module, alias) for every import in one parsed file.

    `from app.harness import client` yields (0, 'app.harness', 'client'), the
    case a reader that records only `node.module` loses: the SUBMODULE is what
    gets loaded, so a forbidden name spelled that way has to be spelled here too.

    `module_level_only` restricts the walk to the file's top-level statements —
    the imports a plain `import` of that module actually executes. Function-local
    imports are a promise about a code path, not a load, and the two scopes carry
    different claims; `test_the_two_import_scopes_disagree_on_purpose` prints the
    difference rather than hiding it.
    """
    nodes = list(tree.body) if module_level_only else list(ast.walk(tree))
    out = []
    for node in nodes:
        if isinstance(node, ast.Import):
            for alias in node.names:
                out.append((0, None, alias.name))
        elif isinstance(node, ast.ImportFrom):
            for alias in node.names:
                out.append((node.level or 0, node.module or None, alias.name))
    return out


def _resolve_target(root: Path, level: int, module: "str | None", alias: str,
                    from_file: Path) -> "Path | None":
    """The first-party file an import loads, or None when it is not in this tree.

    Rooted at the repo root, never at the importing file's directory: `import
    app.component_manifest` means `<root>/app/component_manifest.py`. Relative
    imports are the exception that does resolve against the importer, and both
    spellings of a `from pkg import name` are tried because `name` may be a
    submodule or an attribute of the package that is itself imported first.
    """
    if level:
        base = from_file.parent
        for _ in range(level - 1):
            base = base.parent
        parts = ([module] if module else []) + [alias]
    else:
        base = root
        parts = (module.split(".") if module else []) + [alias]
    candidates = []
    cand = base.joinpath(*parts) if parts else base
    candidates += [cand.with_suffix(".py"), cand / "__init__.py"]
    if not level and module:
        pkg = base.joinpath(*module.split("."))
        candidates += [pkg.with_suffix(".py"), pkg / "__init__.py"]
    for candidate in candidates:
        try:
            if candidate.is_file():
                return candidate
        except OSError:
            continue
    return None


def _parent_package_inits(root: Path, target: Path) -> "list[Path]":
    """The `__init__.py` files Python executes to load `target`.

    `from app.harness.rpc_policy import enabled` runs `app/harness/__init__.py`
    BEFORE the named module, and on this box that `__init__` imports
    `run_query` — which is why a walker that only follows the named module
    reports a clean graph the interpreter never actually walks. Any claim about
    what the probe loads is wrong without these, so the walk visits them too.
    """
    try:
        rel = Path(target).relative_to(root)
    except ValueError:
        return []
    out = []
    for depth in range(1, len(rel.parts)):
        init = root.joinpath(*rel.parts[:depth]) / "__init__.py"
        if init.is_file():
            out.append(init)
    return out


def _dotted(root: Path, path: Path) -> str:
    """The importable dotted name of a first-party file, `__init__` folded away."""
    parts = list(Path(path).relative_to(root).parts)
    if parts[-1] == "__init__.py":
        parts.pop()
    else:
        parts[-1] = parts[-1][:-3]
    return ".".join(parts)


def _closure(start: Path, *, root: Path = ROOT,
             module_level_only: bool = True) -> "dict[str, Any]":
    """The first-party import closure of one file, with what pulled in what.

    Returns names, files and the edge map, because the three support three
    different claims: the names say what is reachable, the file count says the
    walk was not empty, and the edge map says WHO brought a name in — which is how
    `test_the_engine_modules_in_the_deep_closure_arrive_through_a_path_the_probe
    _never_calls` can name the caller instead of asserting a blanket reachability
    it cannot justify.
    """
    names: "dict[str, Path]" = {}
    parents: "dict[str, str]" = {}
    files: "set[Path]" = set()
    pending = [start]
    while pending:
        current = pending.pop()
        if current in files:
            continue
        files.add(current)
        here = _dotted(root, current)
        names.setdefault(here, current)
        try:
            tree = ast.parse(current.read_text(encoding="utf-8"))
        except (OSError, SyntaxError):
            continue
        for level, module, alias in _imports_of(tree, module_level_only):
            target = _resolve_target(root, level, module, alias, current)
            if target is None:
                continue
            for loaded in _parent_package_inits(root, target) + [target]:
                parents.setdefault(_dotted(root, loaded), here)
                if loaded not in files:
                    pending.append(loaded)
    return {"names": names, "files": files, "parents": parents}


def _hits(names, forbidden: "tuple[str, ...]") -> "set[str]":
    """Names that ARE a forbidden module or live beneath it.

    Matched on a dot boundary so `app.harness.client2` is not flagged as
    `app.harness.client` while `app.harness.client.session` is.
    """
    return {n for n in names for f in forbidden
            if n == f or n.startswith(f + ".")}


