def test_probe_matches_a_step_whose_rows_round_trip(tmp_path, monkeypatch):
    """A stored history array, reduced to wire keys, hashes to what was sent.

    The positive case for the whole instrument: nothing is stored here that the
    probe is not allowed to read, and the verdict is `matched` because the
    reconstruction equals the manifest's digests — not because the fixture
    skipped the comparison.
    """
    rows = [dict(USER_ROW), dict(ASSISTANT_ROW),
            {"role": "tool", "tool_call_id": "c1", "content": "spill body"}]
    session, line = _make_step(session_id="20261010_060000_youtubediges_ab01",
                               rows=rows, iteration=1)
    root = _write_sessions(tmp_path, {session["session_id"]: session})
    store = _write_store(tmp_path, {INSIDE_DAY: [line]})
    _pin_rebuild(monkeypatch)

    record = srf.probe_step(session["session_id"], "1", root=root, store=store)

    assert record["verdict"] == "matched"
    assert record["request_id"] == line["request_id"]
    assert record["recorded_sha256"] == record["reconstructed_sha256"]
    assert record["recorded_sha256"].startswith("sha256:")
    # The compared value is the ordered list of the line's own digests: a reader
    # can recompute it from the manifest line with no session file at all.
    assert record["recorded_sha256"] == srf.array_sha256(
        [row["sha256"] for row in line["messages"]])
    assert record["recorded_messages"] == 4 and record["reconstructed_messages"] == 4


