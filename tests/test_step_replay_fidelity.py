def _bytes(text: str) -> int:
    """UTF-8 byte count, which is what a manifest line's `bytes` field reports."""
    return len(text.encode("utf-8", "replace"))


def _component_rows(texts=COMPONENT_TEXTS):
    """Manifest `components[]` rows in render order, from `component_manifest`."""
    return [{"name": name,
             "bytes": _bytes(texts[name]),
             "sha256": component_manifest.digest_text(texts[name]),
             "truncated": False}
            for name in texts]


def _rebuilt_components(texts=COMPONENT_TEXTS):
    """What `live_component_digests` would hand back for those components."""
    return {name: {"bytes": _bytes(texts[name]),
                   "sha256": component_manifest.digest_text(texts[name]),
                   "truncated": False}
            for name in texts}


def _wire(row):
    return {key: row[key] for key in srf.WIRE_KEYS if key in row}


def _make_step(*, session_id, rows, iteration, texts=COMPONENT_TEXTS):
    """A session dict plus a manifest line whose digests ARE the fixture's.

    `rows` are the persisted session rows (extra keys allowed — the probe must
    drop them); the manifest line is built from the same rows through
    `component_manifest.canonical_json`, so an equal reconstruction is a fact
    about the probe, not a tautology about this file.
    """
    system = "\n\n".join(texts[name] for name in texts)
    wire = [{"role": "system", "content": system}] + [_wire(row) for row in rows]
    messages = [{"index": index,
                 "role": message["role"],
                 "bytes": _bytes(
                     component_manifest.canonical_json(message)),
                 "sha256": component_manifest.digest_text(
                     component_manifest.canonical_json(message))}
                for index, message in enumerate(wire)]
    line = {
        "ts": f"{INSIDE_DAY}T06:00:00+00:00",
        "request_id": f"r-fixture-{session_id}-{iteration}",
        "session_id": session_id,
        "source": srf.source_of(session_id),
        "provider": "vllm", "model": "qwen3.6-27b", "platform": "lloyd-web",
        "experiment_id": None,
        "send_site": "app/harness/loop.py:run_query",
        "iteration": iteration,
        "params": {"max_tokens": 4096, "temperature": None},
        "tools": {"bytes": 100, "sha256": "sha256:" + "0" * 64, "count": 2},
        "components": _component_rows(texts),
        "components_captured": True,
        "prefetch": {"bytes": 0, "sha256": "sha256:" + "1" * 64, "present": False},
        "messages": messages,
        "counts": {"prompt_tokens_est": 10, "messages": len(messages),
                   "tool_defs": 2, "components": len(texts)},
    }
    session = {"session_id": session_id, "created_at": "2026-10-10T23:00:00-07:00",
               "platform": "lloyd-web", "messages": rows}
    return session, line


def _write_store(tmp_path, lines_by_day):
    store = tmp_path / "store"
    (store / "manifests").mkdir(parents=True, exist_ok=True)
    for day, lines in lines_by_day.items():
        (store / "manifests" / f"{day}.ndjson").write_text(
            "".join(json.dumps(line) + "\n" for line in lines), encoding="utf-8")
    return store


def _write_sessions(tmp_path, sessions):
    root = tmp_path / "sessions"
    root.mkdir(parents=True, exist_ok=True)
    for session_id, session in sessions.items():
        (root / f"{session_id}.json").write_text(json.dumps(session), encoding="utf-8")
    return root


def _pin_rebuild(monkeypatch, texts=COMPONENT_TEXTS, vault="vault-under-test"):
    """Pin the live rebuild so a component moving is the fixture's doing.

    `_rebuild` reads the real vault, so leaving it live would make every
    component test depend on what someone edited in `~/obsidian` today.
    """
    components = _rebuilt_components(texts)
    prompt = "\n\n".join(texts[name] for name in texts)
    monkeypatch.setattr(srf, "_rebuild",
                        lambda platform: {"prompt": prompt,
                                          "components": components,
                                          "vault_root": vault})


