def _the_probe_itself_imports_no_engine_module() -> None:
    """No import STATEMENT in the probe — at any nesting depth — names an engine module.

    Grepping the file for the dotted name would be the wrong instrument: this
    module's docstring discusses `app.harness.client` by name precisely to say it
    is unreachable, and prose is not a load. So the probe's own tree is parsed and
    every `import` / `from-import` is resolved, function-local ones included, and
    the resulting dotted names are matched against the forbidden list.
    """
    path = ROOT / "eval" / "step_replay_fidelity.py"
    tree = ast.parse(path.read_text(encoding="utf-8"))
    formed = set()
    for level, module, alias in _imports_of(tree, module_level_only=False):
        target = _resolve_target(ROOT, level, module, alias, path)
        if target is not None:
            formed.add(_dotted(ROOT, target))
        elif not level and module:
            formed.add(f"{module}.{alias}")
            formed.add(module)
        elif not level:
            formed.add(alias)
    assert _hits(formed, FORBIDDEN_MODULES) == set(), \
        f"the probe names an engine module in an import: {sorted(formed)}"


