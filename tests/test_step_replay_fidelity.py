def test_a_full_probe_run_mutates_no_store(tmp_path, monkeypatch):
    """Sessions, event logs and the manifest store are byte-identical after a run.

    Every file under all three is hashed before and after a probe and a report
    run over the same corpus. The fixture manifest store is the one that can be
    asserted honestly: the live store is append-only and a busy box is writing
    lines into it while this runs, so a live fingerprint could only ever show a
    difference the probe did not cause — and the probe writing there would show
    up as a new line in the fixture store, which is exactly what is checked.
    """
    sessions, root, logs, store = _corpus_stores(tmp_path)

    # The REAL rebuild, not a pinned one: `components_for` returns nothing so
    # `_rebuild` runs `build_system_prompt` for every probed step. Pinning the
    # digests here would have made the only state-touching call in the probe
    # unexercised — the probe would report `mismatched` from an empty component
    # set, still byte-identical, and the clause would have been proven about a
    # run that never made the call the clause is about.
    monkeypatch.setattr(component_manifest, "components_for",
                        lambda session_id: {})
    monkeypatch.setattr(srf, "_REBUILD", {})
    dirs = [root, logs, store]
    before = _store_fingerprint(dirs)

    code = srf.main(["probe", "--session", list(sessions)[0], "--step", "1",
                     "--sessions-dir", str(root), "--store", str(store)])
    assert code == 0
    srf.main(["report", "--source", "youtube-digest", "--max-sessions", "5",
              "--sessions-dir", str(root), "--store", str(store)])

    assert _store_fingerprint(dirs) == before


