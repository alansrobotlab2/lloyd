def _store_fingerprint(dirs: list[Path]) -> dict[str, str]:
    """`{path: sha256(content)}` for every file under `dirs`, missing dirs skipped."""
    out: dict[str, str] = {}
    for base in dirs:
        if not base.exists():
            continue
        for path in sorted(base.rglob("*")):
            if path.is_file():
                out[str(path.relative_to(base))] = hashlib.sha256(
                    path.read_bytes()).hexdigest()
    return out


