def test_the_report_prints_every_number_the_clause_names(tmp_path, monkeypatch,
                                                         capsys):
    """The printed form is what a human or a log reads, so it carries every figure.

    Clause 5 names eight things: the window, the `retention_days` behind it, and per
    source `sessions_seen`, `steps_probed`, `steps_matched`, `steps_mismatched`,
    `steps_skipped_outside_window`, and the wall seconds. The node that used to
    stand here asserted three of them, so a report that dropped `sessions_seen` or
    `retention_days` — the two a reader needs to tell "this corpus is small" from
    "this corpus was pruned" — still passed it.

    The literals are fixture-owned, not measured off the live tree: `_corpus` writes
    three sessions, two inside the window and one older than it, and edits one of the
    two inside ones so it can no longer match. Those facts are what the assertions
    quote, so a report that silently stopped counting a store it read shows up as a
    wrong number here rather than as a smaller corpus in the field.
    """
    root, store = _corpus(tmp_path)
    _pin_rebuild(monkeypatch)

    code = srf.main(["report", "--source", "youtube-digest",
                     "--sessions-dir", str(root), "--store", str(store)])
    out = capsys.readouterr().out

    assert code == 0
    for expected in ("sessions_seen=3", "steps_probed=2", "steps_matched=1",
                     "steps_mismatched=1", "steps_skipped_outside_window=1"):
        assert expected in out, out
    assert "seconds=" in out and "no model request issued" in out, out

    # The window and the retention it is derived from, checked against each other
    # rather than against a date: the sweep's arithmetic is `today - (retention - 1)`,
    # so a printed window that is not that wide is either a different retention than
    # the one used or a cutoff computed off a different clock.
    days = re.search(r"retention_days=(\d+)", out)
    window = re.search(r"window=(\d{4}-\d{2}-\d{2})\.\.(\d{4}-\d{2}-\d{2})", out)
    assert days and window, out
    cutoff, newest = (date.fromisoformat(g) for g in window.groups())
    assert (newest - cutoff).days == int(days.group(1)) - 1, (
        f"window {cutoff}..{newest} is {(newest - cutoff).days + 1} days wide, "
        f"not the {days.group(1)} the same run printed")


