def test_manifest_store_follows_the_writers_precedence(tmp_path, monkeypatch):
    """The probe reads the store the writer writes, override for override.

    `component_manifest.store_root()` resolves `$LLOYD_MANIFEST_STORE`, then
    `harness.component_manifest.store_dir`, then `$XDG_STATE_HOME`, then
    `Path.home()`. A reader that silently ignored one of those answers
    "no_manifest_line" for a store that exists, which a report cannot tell an
    empty corpus. The last step is the one place the probe deviates on purpose:
    `Path.home()` is the round's symlink farm inside a round, so the fallback is
    `ACCOUNT_HOME` instead, and the test proves the deviation with `$HOME`
    pointed somewhere else.
    """
    env_only = tmp_path / "env-store"
    monkeypatch.setenv("LLOYD_MANIFEST_STORE", str(env_only))
    assert srf.manifest_store() == env_only

    monkeypatch.delenv("LLOYD_MANIFEST_STORE")
    cfg_dir = tmp_path / "cfg-store"
    monkeypatch.setattr(srf.component_manifest, "_cfg",
                        lambda: {"store_dir": str(cfg_dir)}, raising=False)
    assert srf.manifest_store() == cfg_dir

    monkeypatch.setattr(srf.component_manifest, "_cfg", lambda: {}, raising=False)
    xdg = tmp_path / "xdg-state"
    monkeypatch.setenv("XDG_STATE_HOME", str(xdg))
    assert srf.manifest_store() == (
        xdg / srf.component_manifest.DEFAULT_SUBDIR)

    monkeypatch.delenv("XDG_STATE_HOME")
    monkeypatch.setattr(srf, "ACCOUNT_HOME", tmp_path / "account")
    assert srf.manifest_store() == (
        tmp_path / "account" / ".local" / "state"
        / srf.component_manifest.DEFAULT_SUBDIR)


