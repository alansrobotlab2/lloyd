def test_a_mismatch_names_the_vault_the_rebuild_actually_read(tmp_path, monkeypatch,
                                                              capsys):
    """Clause 2's second half: the blame is unreadable without the root it came from.

    `moved_component=skills_index` means two opposite things depending on which vault
    the rebuild could see. Read from the live vault it says the skills really changed
    since the step was sent — a genuine reconstruction gap. Read from a round's
    sibling vault, or none at all, it says the rebuild was composing other text
    entirely and the mismatch is about the harness, not the code. The probe prints
    its root; this pins that the REPORT does too, because the report is what answers
    the item's step-1 question and a reader of the report alone cannot tell the two
    apart. The root is the fixture's own invented path, so no assertion here can be
    satisfied by a hard-coded `~/obsidian`.
    """
    root_path = "/vault/that/was/actually/read"
    drifted = dict(COMPONENT_TEXTS)
    drifted["skills_index"] = drifted["skills_index"] + "\n# edited today\n"
    _pin_rebuild(monkeypatch, drifted, vault=root_path)

    session, line = _make_step(session_id="20261010_060000_youtubediges_vz01",
                               rows=[dict(USER_ROW)], iteration=1)
    root = _write_sessions(tmp_path, {session["session_id"]: session})
    store = _write_store(tmp_path, {INSIDE_DAY: [line]})

    record = srf.probe_step(session["session_id"], "1", root=root, store=store)
    assert record["verdict"] == "mismatched"
    assert record["moved_component"] == "skills_index"
    assert record["vault_read"] == root_path, \
        "the record names a moved component but not the vault it was compared against"
    assert root_path in srf.format_probe(record)

    code = srf.main(["report", "--source", "youtube-digest",
                     "--sessions-dir", str(root), "--store", str(store)])
    out = capsys.readouterr().out
    assert code == 0
    assert f"vault_read={root_path}" in out, (
        "the report's printed form carries `moved_component` but not the root it came "
        "from, which is the ambiguity clause 2 refuses to leave")
    printed = [l for l in out.splitlines() if "vault_read=" in l]
    assert len(printed) == 1, f"the root should be stated once, per run: {printed}"


