"""What `eval/step_replay_fidelity.py` (#2636) is pinned to do.

Four clauses, each with a fixture that gives it a known answer:

1. `probe --session <id> --step <n>` reconstructs a step's outgoing messages
   array and records matched/mismatched with the sha256 compared and the
   manifest `request_id` it was compared against.
2. When a reconstruction does not match, the report names the FIRST manifest
   component whose hash moved, rather than emitting a bare mismatch.
3. The probe issues no model request and mutates nothing: no engine-client
   import reachable from the module, and a full run over a fixture corpus
   leaves the sessions, event-log and request-manifest stores byte-identical.
4. `report --source <src>` prints, per source, the count of steps whose
   reconstruction hash-matches inside the manifest retention window and the
   count skipped as outside it.

Everything the fixture asserts is generated by `app.component_manifest`'s own
digest functions, so a test that passes does so because the probe and the
writer agree, not because the test guessed the same arithmetic twice.
"""

