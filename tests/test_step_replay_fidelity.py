def test_both_witness_fixtures_are_tracked_despite_the_root_json_rule():
    """The extract must be in the tree, and this is the only thing that says so.

    The root `.gitignore` ends with `*.json` — right for runtime data, wrong for the
    one directory whose job is to hold witnesses — and `tests/fixtures/.gitignore`
    un-ignores named families. The session extract rides the `session_witness_*.json`
    family because that family is what it is: an extract of a session transcript
    rather than the transcript, kept because the vault copy is unreachable from a
    node. A family nobody re-reads is how #2282 lost a round: `git add` of an ignored
    fixture does nothing at all, the module then reads a missing file, and the review
    graded correct production code "partial — the pinning node cannot run".

    Both halves are asked of the real mechanism rather than of a belief about it: the
    name must survive `git check-ignore`, and it must be in `git ls-files`. The second
    is the one that catches a negation that fires while the file was never committed,
    which is the state in which the suite is greenest and the witness most absent.
    """
    for fixture in (WITNESS_SESSION_PATH, WITNESS_LINE_PATH):
        rel = f"tests/fixtures/{fixture.name}"
        assert fixture.exists(), f"{rel} is missing from the working tree"
        check = subprocess.run(["git", "-C", str(ROOT), "check-ignore", "-q", "--", rel],
                               capture_output=True, text=True)
        assert check.returncode != 0, \
            f"{rel} is ignored by the root `*.json` rule, so a fresh clone has none"
        listed = subprocess.run(["git", "-C", str(ROOT), "ls-files", "--", rel],
                                capture_output=True, text=True)
        assert listed.stdout.strip() == rel, \
            f"{rel} is not committed (`git ls-files` says {listed.stdout.strip()!r})"


