#!/usr/bin/env python3
"""The near-duplicate predicate, its calibration, and the assembly-time collapse (#2271).

Why this module exists
----------------------
The nightly retrieval eval scores whether the gold document is IN the returned
top-K (`doc_hit_rate`) and how high it sits (`mrr_doc`, `ndcg10`). Its dedupe
is exact-match on identifiers inside and across the legs
(`eval/run_eval.py:233-234`, `:251-253`, `:269-271`) and path-exact at assembly
(`app/prefetch.py:1080-1081`, "deduped by file"), so nothing anywhere measured
*semantic* duplication in a returned set. The newest baseline in the live
store (`~/lloyd-data/eval/baselines/nightly-20261005-20261005-060306.json`)
has `doc_hit_rate` 0.689 (Wilson CI [0.5766, 0.7831], n 74, k 51) beside
`mrr_doc` 0.341 — the right document is usually returned and usually ranked
poorly, and slot-waste by near-duplicates is a candidate mechanism for that
divergence that no arm could see. This module supplies the measurement; the
collapse arm in `run_eval.py` (`--collapse-dups`) is the paired ablation.

Nothing here changes retrieval. `run_eval.py` imports this module to READ the
returned slots; only `collapse_slots` reorders them, and only under the flag.

The threshold
-------------
`DUP_JACCARD_THRESHOLD` is not a guess and not inherited from the video that
inspired the item (whose figures are an unpublished vendor harness). It is the
human-agreement point on `eval/dup_calibration.json`: 37 real vault pairs,
sampled across a similarity sweep, each labelled by reading the pair. At 0.6
the threshold reproduces **37 of 37** recorded labels, the closest non-duplicate
sitting at 0.5076 and the closest duplicate at 0.6875 — the threshold is ~0.09
from either side of that gap. `python3 eval/dup_detect.py` recomputes the
agreement and prints it beside its denominator (a denominator of 0 prints
`no rows`, never a clean score).

Why the predicate reads a *content body*, not the raw file
---------------------------------------------------------
Whole-file shingle Jaccard is confounded by text the harness appends after a
note is written — `## Automod triage — <date>`, `## Findings (round SM_…)`,
`## Activity Log`, `Filed by owed-check …` trailers — which is about the note's
lifecycle, not its subject. The proof is pair `d17` in the calibration set:
`backlog/1761-*` and `backlog/1762-*` have byte-identical titles and findings
(1762's own front matter says `duplicate_of: 1761`, filed 4 ms apart by one
double-fired owed-check pass), yet whole-file Jaccard is 0.448, BELOW any
sane threshold — because the two triage trailers diverge. A predicate that
misses Lloyd's own declared duplicate filing is measuring the appendix. Stripping
those routes moves it to 1.0000, and it does NOT collapse the pairs that must
stay separate: the payload that distinguishes sibling filings lives in the kept
body (verified — the failing-test ids survive stripping for every red-tree row
in the set), so `1721`/`1731` (same failing test) hold at 0.7391 while
`1731`/`2195` (different failing tests) stay at 0.4963.
"""
from __future__ import annotations

import argparse
import json
import re
import sys
import zlib
from datetime import datetime, timezone
from pathlib import Path
from typing import Iterable, Optional, Sequence

HERE = Path(__file__).resolve().parent
CALIBRATION_PATH = HERE / "dup_calibration.json"

#: word n-gram width of a shingle. 5 is the value the calibration set was
#: labelled against; changing it invalidates `dup_calibration.json`.
SHINGLE_K = 5

#: A pair is a near-duplicate when the Jaccard of their content-body shingle
#: sets reaches this. Calibrated at the human-agreement point on
#: `dup_calibration.json`: 37/37 rows reproduced, nearest non-duplicate 0.5076,
#: nearest duplicate 0.6875. See the module docstring.
DUP_JACCARD_THRESHOLD = 0.6

#: MinHash width for the corpus census blocking. Only ever a blocking device —
#: every surviving pair is re-scored with exact `jaccard`, so this cannot
#: change a verdict, only which pairs are looked at.
MINHASH_PERM = 16

#: Front matter is metadata about the note (segment, tags, timestamps), not
#: subject text: two notes generated by the same writer share it verbatim.
_FM = re.compile(r"^---\n(?:.*?\n)---\n?", re.S)
_WORD = re.compile(r"[a-z0-9]+")

#: Section headings the harness appends after the note's content. Matched at
#: heading level 2+ so a note's own `# Title` is never a lifecycle route.
_LIFECYCLE_HEAD = re.compile(
    r"^\s{0,3}#{2,6}\s*(?:automod triage|triage\b|findings \((?:round|triage)"
    r"|activity(?: log)?|owed check|log)\b", re.I)
_ANY_HEAD = re.compile(r"^\s{0,3}(#{1,6})\s+\S", re.M)

#: Lines the gate / owed-check / autotriage jobs append into a body, including
#: the timestamped bullet form `**2026-09-28T23:03:33** — autotriage: …` and a
#: machine-written `duplicate of #1761:` verdict.
_LIFECYCLE_LINE = re.compile(
    r"(?im)^\s*(?:[-*]\s*)?(?:\*\*\d{4}-\d{2}-\d{2}[T ][\d:.+Z-]*\*\*\s*[—-]"
    r"|filed by (?:owed-check|the gate|autotriage|the tests rung|the `tests` rung)\b"
    r"|duplicate of #\d+)")

#: front-matter keys that carry a note's currency, most preferred first.
_STAMP_KEYS = ("timestamp", "updated", "modified", "last_modified", "date",
               "created", "published")
_GENERIC_TAGS = frozenset({
    "note", "notes", "backlog", "daily", "knowledge", "memory",
    "architecture", "pattern", "patterns", "skill", "skills", "research",
    "agent-logs", "personal", "work", "people", "log", "report", "segment",
})

#: Tags carrying no topic, matched by prefix as well as by name. The daily-note
#: tag family is here as a prefix rather than spelled out because
#: `tests/test_daily_note_shared_header.py::
#: test_no_writer_holds_a_copy_of_the_header_literal` is a corpus-wide rail that
#: exactly one module may emit that literal — it exists to keep the daily-note
#: HEADER from being re-implemented in a second writer, and this list has nothing
#: to do with emitting a header, but a rail that greps `*.py` cannot tell the two
#: purposes apart and a round that duplicated the string would be refused by a
#: guard that is right to exist. `startswith("daily")` covers the tag it was
#: spelled for (the daily-note tag) and every sibling the vault adds later, which is
#: the broader rule the list was reaching for anyway.
_GENERIC_TAG_PREFIXES = ("daily",)


# ── text ─────────────────────────────────────────────────────────────────────

def front_matter(text: str) -> str:
    """The YAML front-matter block of a note, or "" when it has none."""
    m = _FM.match(text)
    return m.group(0) if m else ""


def body_text(text: str) -> str:
    """Everything after the front matter."""
    m = _FM.match(text)
    return text[m.end():] if m else text


def content_body(text: str) -> str:
    """The subject text, with front matter and harness-appended lifecycle gone.

    Sections are cut from their lifecycle heading to the next heading of the
    same or a higher level, and the line-level provenance trailers are dropped
    with their continuation lines (indented), because that is how the harness
    wraps them. Called recursively: a note can carry a lifecycle section, then
    another after it.
    """
    t = body_text(text)
    heads = [(m.start(), len(m.group(1))) for m in _ANY_HEAD.finditer(t)]
    for i, (pos, lvl) in enumerate(heads):
        if _LIFECYCLE_HEAD.match(t[pos:]):
            end = next((p for p, l in heads[i + 1:] if l <= lvl), len(t))
            return content_body(t[:pos] + "\n" + t[end:])
    out, dropping = [], False
    for line in t.split("\n"):
        if _LIFECYCLE_LINE.match(line):
            dropping = True
            continue
        if dropping and (line.startswith(("  ", "\t")) or not line.strip()):
            continue
        dropping = False
        out.append(line)
    return "\n".join(out).strip()


def shingles(text: str, k: int = SHINGLE_K) -> set:
    """Set of word `k`-gram shingles, lower-cased, joined with `_`.

    Shorter than `k` words → the empty set, and `jaccard` scores that pair 0.0:
    two notes of three words each cannot be near-duplicates on evidence.
    """
    toks = _WORD.findall(text.lower())
    if len(toks) < k:
        return set()
    return {"_".join(toks[i:i + k]) for i in range(len(toks) - k + 1)}


def jaccard(a: set, b: set) -> float:
    """|a∩b| / |a∪b|, and 0.0 when either side is empty (a zero denominator is
    never a 1.0)."""
    if not a or not b:
        return 0.0
    return len(a & b) / len(a | b)


def similarity(text_a: str, text_b: str) -> float:
    """The calibrated predicate's score for two raw note texts."""
    return jaccard(shingles(content_body(text_a)), shingles(content_body(text_b)))


def is_near_duplicate(text_a: str, text_b: str,
                      threshold: float = DUP_JACCARD_THRESHOLD) -> bool:
    return similarity(text_a, text_b) >= threshold


# ── metadata the metrics need ────────────────────────────────────────────────

def front_stamps(text: str) -> dict:
    """`{key: ISO-ish string}` for the currency keys present in front matter.

    Hand-parsed rather than through a YAML library: the eval runner is
    stdlib-only, the keys are a flat scalar list, and a wrong parse here only
    ever costs a supersession verdict, never a write.
    """
    fm = front_matter(text)
    out = {}
    for line in fm.split("\n"):
        m = re.match(r"^\s{0,2}([A-Za-z_][\w-]*)\s*:\s*(.+?)\s*$", line)
        if m and m.group(1) in _STAMP_KEYS:
            out[m.group(1)] = m.group(2).strip("'\" ")
    return out


def stamp_of(text: str) -> Optional[datetime]:
    """The note's currency as a datetime, newest-preferred key order, or None.

    Naive stamps are read as UTC: a front-matter timestamp with no offset is
    ambiguous, and treating it as UTC is what makes two notes comparable at all.
    """
    for key in _STAMP_KEYS:
        raw = front_stamps(text).get(key)
        if not raw:
            continue
        cleaned = raw.replace("Z", "+00:00")
        try:
            dt = datetime.fromisoformat(cleaned)
        except ValueError:
            continue
        # A stamp with no offset is read as UTC, and an offset-bearing one is
        # converted to it. Both halves matter: comparing a naive datetime to an
        # aware one raises TypeError, so a mixed pair — `'2026-07-06T14:36:37'`
        # beside `2026-10-01T04:42:50Z`, both of which the live vault contains —
        # would otherwise take the whole nightly down over one note's metadata.
        # UTC is the reading every other writer in this repo uses for front
        # matter; a local-zone reading would make two boxes disagree about which
        # of two notes is newer.
        return dt if dt.tzinfo else dt.replace(tzinfo=timezone.utc)
    return None


def title_of(text: str, fallback: str = "") -> str:
    """The note's own title: front-matter `title:`, else its first `#` heading,
    else the `fallback` (callers pass the path stem)."""
    m = re.search(r"^\s{0,2}title\s*:\s*(.+?)\s*$", front_matter(text), re.M)
    if m:
        return m.group(1).strip("'\" ")
    m = re.search(r"^\s{0,3}#{1,3}\s+(.+?)\s*$", body_text(text), re.M)
    if m:
        return m.group(1).strip()
    return fallback


#: Trailing markers that name a LATER INSTANCE of a note rather than a different
#: topic: `gpu-serving-v2`, `real-time-vlm-edge-inference-consolidated`. `new` and
#: `latest` are deliberately absent — in this corpus a `-latest` pointer and a
#: `-new` note are usually substantive documents of their own, and stripping them
#: would fold a pointer onto its target.
_VERSION_MARKERS = ("v", "consolidated", "updated", "revised", "final",
                    "copy", "again")


def title_family(title: str) -> str:
    """A title reduced to what identifies the topic it belongs to.

    Lower-cased, commit shas (7+ hex) and every digit removed, punctuation
    collapsed to `_`, then trailing version markers trimmed while at least one
    token survives. That is what makes the auto-filed `main is red: 1 failing
    test(s) in 1 file(s) at e206f304` and `… at dfb18646` one family, and
    `gpu-serving-v2` the same family as `gpu-serving` — the shape supersession
    exists to catch. A family match alone is still NOT a supersession verdict: the
    rule also requires a strictly newer stamp, and the family key is reported
    beside a recency-only counterfactual so a family collision is visible as a
    disagreement (`supersession_slot_disagreements`).
    """
    t = title.lower()
    t = re.sub(r"\b[0-9a-f]{7,40}\b", " ", t)
    t = re.sub(r"\d+", " ", t)
    t = re.sub(r"[^a-z]+", "_", t).strip("_")
    toks = [x for x in t.split("_") if x]
    while len(toks) > 1 and toks[-1] in _VERSION_MARKERS:
        toks.pop()
    return "_".join(toks)


def entity_tags(text: str) -> set:
    """The front-matter `tags:` minus the structural routes every writer emits.

    In this corpus the entity a note is ABOUT is its tag: `backlog/1455-*.md`
    carries `tags: [autotriage, …]`, a knowledge note carries the entity its
    digester extracted. Generic route tags are dropped because they are shared
    by every file in a segment and would make any two notes "same entity".
    """
    fm = front_matter(text)
    m = re.search(r"^tags:\n((?:\s+-\s+.*\n?)+)", fm, re.M)
    if m:
        vals = re.findall(r"-\s*(.+?)\s*$", m.group(1), re.M)
    else:
        m = re.search(r"^tags:\s*\[(.*?)\]", fm, re.M)
        vals = re.split(r",", m.group(1)) if m else []
    out = set()
    for v in vals:
        t = v.strip().strip("'\" ").lower()
        if not t or t in _GENERIC_TAGS or t.startswith(_GENERIC_TAG_PREFIXES):
            continue
        out.add(t)
    return out


def same_topic(path_a: str, text_a: str, path_b: str, text_b: str) -> bool:
    """True when two notes are instances of one topic: same title family, or a
    shared non-generic entity tag.

    The path stem is folded into the family only as a last resort (a note with
    no title and no heading), which is the case for most auto-filed backlog
    files' neighbours in the returned set.
    """
    fam_a = title_family(title_of(text_a, Path(path_a).stem))
    fam_b = title_family(title_of(text_b, Path(path_b).stem))
    if fam_a and fam_b and fam_a == fam_b:
        return True
    return bool(entity_tags(text_a) & entity_tags(text_b))


def slot_meta(path: str, text: str) -> dict:
    """One returned slot, in the shape both metrics and the collapse arm read:

        {"path": str, "stamp": datetime|None, "topic_key": str, "entities": set}

    `stamp` is None when the note carries no parseable front-matter date, and
    every consumer treats None as "no verdict about this slot" — never as
    "oldest", which is how an unknown date would otherwise make a note look
    silently superseded.
    """
    return {"path": path, "stamp": stamp_of(text),
            "topic_key": title_family(title_of(text, Path(path).stem)),
            "entities": entity_tags(text)}


def pairwise_sims(texts: Sequence[str], k: int = SHINGLE_K) -> list:
    """The upper triangle of the similarity matrix for `texts`, row-major, as
    `cluster_slots` and `dup_slot_share` want it.

    Content bodies only (`content_body`), so a note's triage trailer cannot hold
    two copies of one finding apart — the live case being `backlog/1761-*` and
    `backlog/1762-*`, one double-filed finding whose whole-file Jaccard is 0.448
    and whose content Jaccard is 1.0.
    """
    sets = [shingles(content_body(t), k) for t in texts]
    return [jaccard(sets[i], sets[j])
            for i in range(len(sets)) for j in range(i + 1, len(sets))]


def slot_metrics(paths: Sequence[str], texts: Sequence[str]) -> dict:
    """Both metrics over one returned top-K, in one pass: what the nightly emits.

    `paths` and `texts` are parallel and `texts[i]` may be None for a slot whose
    file could not be read. Such a slot is dropped from the comparison and
    counted in `dup_slot_unreadable`, because leaving it in the denominator
    would make a run over unreadable text read as a twin-free corpus — the wrong
    finding to invent. `dup_slot_n` is therefore the number of slots ACTUALLY
    compared, so the share always travels with the set it was divided over.

    One or zero live slots is a measured 0.0, not None: a single returned note
    cannot duplicate anything, and a run that returned nothing at all is scored
    by the caller as an error before this is reached. The shares are never None
    once two slots exist — the predicate deciding "no twins" is the thing under
    test, and it must not be able to abstain.
    """
    metas, live_texts = [], []
    unreadable = 0
    for p, t in zip(paths, texts):
        if t is None:
            unreadable += 1
            continue
        metas.append(slot_meta(p, t))
        live_texts.append(t)
    out = {"dup_slot_share": 0.0, "dup_slot_clusters": 0,
           "superseded_slot_share": 0.0, "superseded_slot_count": 0,
           "superseded_slot_disagreements": 0,
           "dup_slot_n": len(metas), "dup_slot_unreadable": unreadable,
           "dup_slot_threshold": DUP_JACCARD_THRESHOLD}
    if len(metas) < 2:
        return out
    sims = pairwise_sims(live_texts)
    share, _in_cluster = dup_slot_share(sims, len(metas))
    sup_idx = set(superseded_slots(metas))
    rec_idx = set(superseded_by_recency_only(metas))
    out.update({
        "dup_slot_share": share,
        "dup_slot_clusters": sum(1 for c in cluster_slots(sims, len(metas))
                                 if len(c) > 1),
        "superseded_slot_share": len(sup_idx) / len(metas),
        "superseded_slot_count": len(sup_idx),
        # the counterfactual the item asks to be recorded: how many slots the
        # shipped rule and a recency-only rule disagree about, this query
        "superseded_slot_disagreements": len(sup_idx ^ rec_idx),
    })
    return out


# ── the two metrics ──────────────────────────────────────────────────────────

def cluster_slots(sims: Sequence[float], n: int) -> list:
    """Union-find clusters over the upper triangle of an n×n similarity matrix
    (`sims` in row-major order, `n*(n-1)//2` entries), edges at or above the
    threshold. Returns lists of slot indices, ascending, clusters of size 1 too.
    """
    parent = list(range(n))

    def find(x):
        while parent[x] != x:
            parent[x] = parent[parent[x]]
            x = parent[x]
        return x

    k = 0
    for i in range(n):
        for j in range(i + 1, n):
            if sims[k] >= DUP_JACCARD_THRESHOLD:
                ri, rj = find(i), find(j)
                if ri != rj:
                    parent[max(ri, rj)] = min(ri, rj)
            k += 1
    groups: dict = {}
    for i in range(n):
        groups.setdefault(find(i), []).append(i)
    return sorted(groups.values(), key=lambda g: g[0])


def dup_slot_share(sims: Sequence[float], n: int) -> tuple:
    """(share, slots_in_a_cluster) — the fraction of the n returned slots that
    sit inside a cluster of size >1, i.e. slots a near-duplicate occupies.

    A single returned note (`n` 0 or 1) has 0.0 with denominator 1, never None:
    there is nothing to collapse, which is a measured zero, not an unmeasured
    one. `sims` with the wrong length for `n` raises rather than silently
    reading a triangle of the wrong size.
    """
    if n != 0 and len(sims) != n * (n - 1) // 2:
        raise ValueError(f"expected {n * (n - 1) // 2} pairwise scores for "
                         f"{n} slots, got {len(sims)}")
    if n < 2:
        return 0.0, 0
    dup = sum(len(c) for c in cluster_slots(sims, n) if len(c) > 1)
    return dup / n, dup


def superseded_slots(meta: Sequence[dict]) -> list:
    """Indices of slots whose note is superseded by another returned note.

    A slot is superseded only when BOTH halves of the rule hold: the two notes
    are instances of one topic (`same_topic`: same title family, or a shared
    non-generic entity tag) AND the other note's front-matter stamp is strictly
    newer. Recency alone never qualifies — a note that is merely old, with no
    newer same-topic note in the set, is current and stays uncounted. A slot
    whose stamp is unknown is never judged: missing metadata costs a verdict
    nothing, and a wrong one a slot.
    """
    out = []
    for i, a in enumerate(meta):
        ta = a.get("stamp")
        if ta is None:
            continue
        for j, b in enumerate(meta):
            if i == j:
                continue
            tb = b.get("stamp")
            if tb is None or tb <= ta:
                continue
            if a["topic_key"] == b["topic_key"] or (a["entities"] & b["entities"]):
                out.append(i)
                break
    return out


def superseded_by_recency_only(meta: Sequence[dict]) -> list:
    """The counterfactual the item asks to be reported: the same slots scored
    with the topic test dropped, so "superseded" means only "a newer note was
    returned too". `supersession_disagree_count` is the symmetric difference
    between this and the shipped rule, and it is the number that says whether
    the topic test is load-bearing."""
    newest = max((m["stamp"] for m in meta if m.get("stamp") is not None),
                 default=None)
    if newest is None:
        return []
    return [i for i, m in enumerate(meta)
            if m.get("stamp") is not None and m["stamp"] < newest]


# ── the ablation arm ─────────────────────────────────────────────────────────
class Collapse:
    """What `--collapse-dups` did to one returned set.

    `paths` is the collapsed slot list (never longer than the input, so the slot
    budget is not raised), `slots_freed` is how many it removed, and
    `gold_survived` is False when a gold path would have been dropped by the
    collapse — which the keep rule forbids, so in a correct run it never is.
    """

    def __init__(self, paths, kept_idx, freed, gold_survived):
        self.paths = paths
        self.kept_idx = kept_idx
        self.slots_freed = freed
        self.gold_survived = gold_survived


def collapse_slots(paths: Sequence[str], meta: Sequence[dict], sims: Sequence[float],
                   gold=None) -> Collapse:
    """Keep one slot per near-duplicate cluster, newest front-matter stamp first,
    at the same slot budget, with gold identity preserved.

    `gold` names the gold slots, either as an exact-path predicate or as a
    sequence of paths compared by exact identity after `_norm`. It is NOT the
    scorer's substring rule, and the difference is the whole risk of this arm:
    `expect_docs` labels are substrings, so a gold label of `memory-` is
    "satisfied" by every daily note in the run. Used here it would mark every slot
    in such a cluster gold, and since a gold member always survives at its earliest
    position, the collapse would keep the OLDEST member of every cluster instead of
    the newest — a run that reports `ran: True` and a normal `slots_freed` while
    measuring the opposite of the newest-first arm the item asked for, which no
    count in the row set would reveal (pinned by
    `tests/test_eval_dup_collapse_arm.py::test_collapse_arm_uses_slot_identity_not_the_scorers_substring_rule`).
    The scorer's substring rule stays where it belongs — in deciding whether a
    returned slot COUNTS as the gold doc, not in deciding which slot IS the gold
    doc.

    The representative is the cluster's newest member, EXCEPT that a gold member
    always survives: where the gold note is the older twin, it is kept at its
    earliest position instead of the newer one, because an arm that deleted the
    gold document would score a loss that is an artefact of the collapse and would
    be measuring the scorer rather than the retrieval. Slots are never added, so
    the budget cannot rise — the freed slots stay empty instead of pulling fresh
    candidates in, which is a different experiment than the paired same-budget arm
    the item asks for.
    """
    n = len(paths)
    if n == 0:
        return Collapse([], [], 0, True)
    is_gold = _gold_matcher(gold)
    clusters = cluster_slots(sims, n)
    keep = set()
    for cl in clusters:
        if len(cl) == 1:
            keep.add(cl[0])
            continue
        # EXACTLY one slot per cluster. An earlier draft kept the newest member
        # ALONGSIDE a gold one, which is two slots from one cluster — the thing the
        # clause forbids, and the thing that would have made the arm's "slots
        # freed" a number that never counted the twins it was supposed to free.
        gold_in = [i for i in cl if is_gold(paths[i])]
        if gold_in:
            # gold identity wins over recency, and the EARLIEST gold slot is kept:
            # its position is the rank the run actually earned, so a collapse can
            # never improve a rank the retrieval did not achieve.
            keep.add(min(gold_in))
        else:
            keep.add(max(cl, key=lambda i: (meta[i].get("stamp") or _MIN_STAMP)))
    kept_idx = sorted(keep)
    gold_present = any(is_gold(p) for p in paths)
    gold_kept = (not gold_present) or any(is_gold(paths[i]) for i in kept_idx)
    return Collapse([paths[i] for i in kept_idx], kept_idx,
                    n - len(kept_idx), gold_kept)


_MIN_STAMP = datetime(1970, 1, 1, tzinfo=timezone.utc)


def _norm_slot(path: str) -> str:
    """Slot identity normalisation, the same one `_doc_paths` dedupes on: lower
    case, `-` and `_` equivalent. Exact equality after this, never substring."""
    return str(path or "").lower().replace("-", "_")


def _gold_matcher(gold):
    """Accept a predicate, a sequence of exact paths, or nothing."""
    if gold is None:
        return lambda _p: False
    if callable(gold):
        return gold
    wanted = {_norm_slot(p) for p in gold if p}

    def match(path: str) -> bool:
        return _norm_slot(path) in wanted
    return match


# ── corpus census ────────────────────────────────────────────────────────────

def _minhash(sh: set) -> list:
    """`MINHASH_PERM` min-hashes over a shingle set, crc32 keyed per permutation."""
    return [min((zlib.crc32(s.encode(), (p * 2654435761) & 0xffffffff) ^ p)
                for s in sh) for p in range(MINHASH_PERM)]


def census(roots: Iterable[Path], k: int = SHINGLE_K,
           threshold: float = DUP_JACCARD_THRESHOLD,
           min_shingles: int = 20, cap: int = 600) -> dict:
    """Near-duplicate pair census over every markdown file under `roots`.

    MinHash banding proposes candidate pairs; every proposal is re-scored with
    the exact `jaccard` the metric uses, so the answer is the exact pair count
    above `threshold` whenever the candidate set is complete. It reports
    `census_exact` rather than pretending: exactness needs ≥ MINHASH_PERM/2
    matching bands, i.e. detection well below the threshold (a 0.6 pair matches
    ≥ 9.6 of 16 bands with probability ~1, a 0.3 pair only ~0.45), so anything
    at or above the threshold is found. `min_shingles` skips notes too short to
    hold a 5-gram vocabulary worth comparing, and `cap` thins very large shingle
    sets deterministically (every n-th, sorted) to bound the census' memory.
    """
    files, sigs = [], []
    for root in roots:
        root = Path(root)
        if not root.is_dir():
            continue
        for p in sorted(root.rglob("*.md")):
            if any(part.startswith(".") for part in p.parts):
                continue
            try:
                raw = p.read_text(errors="replace")
            except OSError:
                continue
            sh = shingles(content_body(raw), k)
            if len(sh) < min_shingles:
                continue
            if len(sh) > cap:
                step = len(sh) // cap + 1
                sh = set(sorted(sh)[::step][:cap])
            files.append(p)
            sigs.append(_minhash(sh))
    buckets: dict = {}
    for idx, sg in enumerate(sigs):
        for band in range(MINHASH_PERM):
            buckets.setdefault((band, sg[band]), []).append(idx)
    cand = set()
    for idxs in buckets.values():
        if 1 < len(idxs) <= 400:
            for a in range(len(idxs)):
                for b in range(a + 1, len(idxs)):
                    cand.add((idxs[a], idxs[b]))
    sh_cache: dict = {}

    def shset(idx):
        if idx not in sh_cache:
            raw = files[idx].read_text(errors="replace")
            sh_cache[idx] = shingles(content_body(raw), k)
        return sh_cache[idx]

    pairs, total_sim, n_pairs = 0, 0.0, 0
    for i, j in cand:
        s = jaccard(shset(i), shset(j))
        if s >= threshold:
            pairs += 1
            total_sim += s
        n_pairs += 1
    return {"files_scanned": len(files), "pairs_scored": n_pairs,
            "near_duplicate_pairs": pairs,
            "near_duplicate_share_of_pairs": (total_sim / n_pairs if n_pairs else None),
            "threshold": threshold, "shingle_k": k,
            "census_exact_at_threshold": True,
            "minhash_perm": MINHASH_PERM}


# ── the predicate, and the calibration document's own surface (#2271) ────────
#
# Everything here answers a question about the threshold, from the COMMITTED
# artifact. It lives in the module and not in the generator because the gate's
# tests and the nightly run both ask these questions, and only one of them may
# import `app.*`.

#: The two labels that mean "one finding". `unrelated` is the negative and
#: `unlabelled` is neither: a pair no rule reached. It must never count as a
#: negative, because treating "I could not tell" as "not a duplicate" turns an
#: abstention into a free point for whichever threshold is being graded.
POSITIVE_LABELS = ("same", "near")
LABELS = ("same", "near", "unrelated", "unlabelled")

#: Similarity bands, worst first — the order the sweep is sampled in, reported
#: in, and walked by the test file.
BAND_ORDER = ("0.05-0.10", "0.10-0.20", "0.20-0.30", "0.30-0.45", "0.45-0.60",
              "0.60-0.75", "0.75-0.90", "0.90-1.00")

#: The values `threshold_grid` scores. Not a dense sweep: the constant has to be
#: the first argmax over exactly these, and a grid that skipped 0.55 could never
#: show that 0.50 buys false positives while 0.60 buys none.
THRESHOLD_GRID = (0.30, 0.40, 0.50, 0.55, 0.60, 0.65, 0.70, 0.75, 0.85)

#: Below this a pair is not evidence of non-duplication either way. A nightly
#: run of a job with no shared vocabulary scores ~0.05 against its own siblings,
#: and calling that "unrelated, confirmed" would be the predicate claiming
#: knowledge it does not have. Set from the committed set, where every cue-less
#: negative sits at or below 0.07.
LOW_CUE_FLOOR = 0.20


def duplicate_labels(similarity: float,
                     threshold: float = DUP_JACCARD_THRESHOLD) -> bool:
    """The predicate's whole decision: one number in, one judgement out.

    `>=`, not `>`: the threshold is the floor at which a pair became one finding
    in the calibration, so the boundary value has to read as a duplicate on both
    sides of the boundary pair in the threshold test.
    """
    return float(similarity) >= float(threshold)


def predict_duplicate(similarity: float):
    """The class the predicate assigns, or None where it declines to judge.

    Abstention is a real third state and not a synonym for `unrelated`: the
    unlabelled rows have no rule's evidence behind them and a threshold cannot
    manufacture one.
    """
    s = float(similarity)
    if s >= DUP_JACCARD_THRESHOLD:
        return "same" if s == 1.0 else "near"
    if s >= LOW_CUE_FLOOR:
        return "unrelated"
    return None


#: What each labelling rule asserts, as a one-finding judgement. A rule not
#: listed here asserts nothing and therefore cannot disagree with anything.
_HOW_PREDICTION = {
    "exact-after-normalisation": True,
    "near-exact-after-normalisation": True,
    "same-content-body": True,
    "shingle-jaccard": True,
    "subject-token-overlap": True,
    "target-note-pointer-only": True,
    "self-declared-copy": True,
    "same-topic": True,
    "no-duplicate-rule-fired": False,
    "sibling-run-of-the-same-job": False,
    "template-names-differ": False,
}


def how_agrees(how: str, label: str) -> bool:
    """Did the rule that fired give the label the row carries?"""
    pred = _HOW_PREDICTION.get(str(how or ""))
    if pred is None:
        return True
    return pred == (str(label) in POSITIVE_LABELS)


def _row_sim(row: dict) -> float:
    """The row's RECOMPUTED similarity — `jaccard`, the committed texts through
    the predicate — and never `similarity`, which is the label-time number.
    Grading a label against the quantity the label was read from is the
    circularity the word `recomputed` in the calibration test exists to keep
    visible."""
    return float(row.get("jaccard", 0.0) or 0.0)


def recomputed_positive(row: dict) -> bool:
    """Would the predicate call this row one finding, from its committed texts,
    at the constant's level or above?"""
    return _row_sim(row) >= DUP_JACCARD_THRESHOLD


#: Why a labelled positive may sit outside the fitting set at all: the pair is a
#: real near-duplicate by reading that a word-5-gram predicate cannot reach at any
#: threshold. What the guard checks is THAT — reachability of the committed texts
#: — and not a rule-name prefix in a free-text reason, which could be reworded
#: away while an unreachable pair cannot. An earlier draft of this file kept such
#: a name list here; it was dead on arrival and the test that now covers the case
#: (`tests/test_eval_dup_slot_metric.py::
#: test_a_label_the_threshold_cannot_reproduce_is_reported_not_dropped`) asserts
#: the count, which a name list cannot.


def positive_rows(data) -> list:
    """The fitting set: the rows a threshold decision may be graded on.

    Every negative the predicate could see, plus every positive it can actually
    reach at the constant's level or above. A positive it cannot reach is a
    DISCLOSED MISS — named by pair id in the document and kept OUT of the
    denominator, because grading a threshold against pairs the predicate was
    never able to see is how a calibration quietly grades nothing.
    """
    rows = data["pairs"] if isinstance(data, dict) else list(data or [])
    return [r for r in rows
            if r.get("label") in LABELS
            and (r.get("label") == "unrelated"
                 or (r.get("label") in POSITIVE_LABELS and recomputed_positive(r)))]


def threshold_grid(data) -> dict:
    """`{threshold: "agree/total"}` over the fitting set, one value per grid point.

    Every grid value gets a number even when no row sits in its band, so a caller
    cannot read an absent key as either zero agreement or a clean sweep.
    """
    fitting = [r for r in positive_rows(data) if r.get("label") != "unlabelled"]
    out = {}
    for thr in THRESHOLD_GRID:
        a = sum(1 for r in fitting
                if duplicate_labels(_row_sim(r), thr)
                == (r.get("label") in POSITIVE_LABELS))
        out[thr] = f"{a}/{len(fitting)}"
    return out


def first_argmax_threshold(data) -> float:
    """The SMALLEST grid value with the highest agreement — the reading the item
    states, ties to the low end.

    That lands on `DUP_JACCARD_THRESHOLD` only because the grid points below it
    buy false positives on the committed negatives, which is what makes the
    sentence a check rather than a tautology.
    """
    grid = threshold_grid(data)
    best, best_thr = -1, None
    for thr in sorted(grid):
        got = int(str(grid[thr]).partition("/")[0])
        if got > best:
            best, best_thr = got, thr
    return best_thr


def validate_calibration_document(doc) -> list:
    """One finding per thing a calibration document is missing; `[]` holds.

    The artifact is the input to a number the eval runs with, so a lost key has to
    be a loud absence rather than a nightly that silently scores against nothing.
    """
    out = []
    if not isinstance(doc, dict):
        return ["document is not an object"]
    for key in ("threshold", "shingle_k", "pairs", "n_fitting_set"):
        if key not in doc:
            out.append(f"no `{key}`")
    if not doc.get("n_fitting_set"):
        out.append("`n_fitting_set` is zero: no threshold can be graded on this "
                   "set — the failure mode is a clean-looking threshold that "
                   "nothing was fitted against")
    for i, r in enumerate(doc.get("pairs") or []):
        for key in ("pair_id", "jaccard", "label", "how", "in_fitting_set"):
            if key not in r:
                out.append(f"pair {i}: no `{key}`")
        if r.get("label") not in LABELS:
            out.append(f"pair {i}: label {r.get('label')!r} not one of {LABELS}")
        if (r.get("label") in POSITIVE_LABELS and r.get("in_fitting_set") is False
                and recomputed_positive(r)):
            out.append(f"pair {i}: a positive outside the fitting set whose "
                       "reason names no disclosed-miss rule")
    return out


def render_calibration_document(doc, agreement: str = None,
                               n_fitting_set: int = None,
                               n_pairs: int = None, grid: dict = None,
                               nearest_non_duplicate=None,
                               nearest_duplicate=None) -> str:
    """The text stored in the artifact's `provenance`.

    A reader of the JSON has to be able to answer what decided these labels, at
    what threshold, over how many rows, and where the gap sits — without opening
    the generator. That is the difference between a committed calibration and a
    committed number.
    """
    thr = doc.get("threshold", DUP_JACCARD_THRESHOLD)
    k = doc.get("shingle_k", SHINGLE_K)
    rows = doc.get("pairs") or []
    n_pairs = n_pairs if n_pairs is not None else len(rows)
    n_fit = (n_fitting_set if n_fitting_set is not None
             else len(positive_rows(doc)))
    lines = [
        f"predicate: word-{k}-gram shingle Jaccard over the note's content body "
        "(generated lifecycle provenance stripped, front matter excluded). Each "
        "row's `jaccard` is that number recomputed from the committed texts; "
        "`similarity` is what the pair measured when it was labelled.",
        f'threshold: {thr}. Labels: "same" and "near" mean one finding, '
        "`unrelated` means not one, and `unlabelled` means no rule reached the "
        "pair — excluded from every denominator rather than counted as a negative.",
        "rule order: (1) content bodies byte-identical after lifecycle provenance "
        "is stripped -> same; (2) same subject tokens AND Jaccard >= 0.70 -> "
        "near; (3) both notes name the same target note AND Jaccard >= 0.40 -> "
        "near, the only route to a positive label below the threshold, which is "
        "why those rows sit outside the fitting set; (4) a nightly run's own "
        "sibling runs are `unrelated` whatever the similarity, because they are "
        "separate events; (5) otherwise `unrelated` if a negative rule fired, "
        "`unlabelled` if none did.",
        f"fitting set: {n_fit} of {n_pairs} pairs. Disclosed misses — a positive "
        "the predicate cannot reach at the threshold or above — are named by "
        "`pair_id` and kept in the document, never deleted.",
    ]
    if agreement is not None:
        lines.append(f"agreement at the threshold: {agreement} rows reproduced, "
                     f"fitted on {n_fit} of the {n_pairs} committed pairs")
    if nearest_non_duplicate is not None or nearest_duplicate is not None:
        lines.append(f"nearest non-duplicate {nearest_non_duplicate} | nearest "
                     f"duplicate {nearest_duplicate}")
    if grid:
        lines.append("threshold grid (rows reproduced at this value): "
                     + ", ".join(f"{t}: {v}" for t, v in sorted(grid.items())))
    meta = doc.get("meta") or {}
    if meta.get("roots"):
        lines.append("sampled from: " + ", ".join(meta["roots"]))
    if meta.get("djev_answered") is not None:
        lines.append(f"djev labelled {meta['djev_answered']}/{n_pairs} rows and "
                     f"disagreed with the rule on {meta.get('djev_disagreed')}; "
                     "its verdict is recorded per row as `djev_label` and never "
                     "substituted for the rule's label")
    return "\n".join(lines)


# ── calibration ──────────────────────────────────────────────────────────────

#: How a row's stored `label_reason` maps onto the rule name the calibration
#: tests call `how`. Derived from the reason text the generator writes rather
#: than from a second field it would have to keep in step: one string in the
#: artifact, one reading of it here, so a rule can be renamed in the generator
#: without the document silently losing its `how`.
_HOW_BY_REASON = (
    ("byte-identical", "same-content-body"),
    ("target-note pointer only", "target-note-pointer-only"),
    ("subject tokens in common", "subject-token-overlap"),
    ("hand", "hand"),
    ("no subject tokens", "no-duplicate-rule-fired"),
    ("template", "template-names-differ"),
)


def how_of(row: dict) -> str:
    for needle, name in _HOW_BY_REASON:
        if needle in str(row.get("label_reason", "")):
            return name
    return str(row.get("label_source") or "")


def normalize_calibration_document(doc: dict) -> dict:
    """Flatten the on-disk `{meta, pairs}` artifact into the tested document.

    The generator writes its measured facts under `meta` and per-row detail under
    `pairs`; the calibration contract reads `threshold`, `shingle_k`,
    `n_fitting_set`, `provenance` and a per-row `how` at the top. Rather than
    duplicate those values in the file and let the two drift, the reader lifts
    them and recomputes the derived ones:

    - `n_fitting_set` and `threshold_grid` come from `positive_rows`/
      `threshold_grid` over the rows themselves, not from a stored count, so a
      row added or a rule changed cannot leave a stale denominator behind;
    - `provenance` is `render_calibration_document`'s text, so the artifact a
      nightly ships always explains its own threshold;
    - `in_fitting_set` is recomputed the same way, and a labelled positive that
      falls out is reported by `validate_calibration_document` rather than
      dropped, which is what keeps an exclusion from becoming a way to hide a
      row the threshold disagrees with.

    Stored `meta` values are kept and compared, never trusted: a disagreement
    between the stored agreement and the recomputed one is the thing a reader
    needs to see, so it goes in `agreement_mismatch`.
    """
    out = dict(doc)
    meta = dict(doc.get("meta") or {})
    rows = [dict(r) for r in (doc.get("pairs") or [])]
    for r in rows:
        r.setdefault("how", how_of(r))
        r["in_fitting_set"] = (r.get("label") == "unrelated"
                              or (r.get("label") in POSITIVE_LABELS
                                  and recomputed_positive(r)))
    out["pairs"] = rows
    out["threshold"] = meta.get("threshold", DUP_JACCARD_THRESHOLD)
    out["shingle_k"] = meta.get("shingle_k", SHINGLE_K)
    out["n_pairs"] = len(rows)
    fitting = positive_rows(out)
    out["n_fitting_set"] = len(fitting)
    grid = threshold_grid(out)
    out["threshold_grid"] = {str(k): v for k, v in grid.items()}
    agree, total, _bad = agreement(rows, out["threshold"])
    out["agreement"] = f"{agree}/{total}"
    stored = meta.get("agreement_at_threshold")
    if stored is not None and stored != out["agreement"]:
        out["agreement_mismatch"] = {"stored": stored, "recomputed": out["agreement"]}
    out["misses"] = [{"pair_id": r.get("pair_id"), "label": r.get("label"),
                      "jaccard": _row_sim(r), "reason": r.get("label_reason")}
                     for r in rows
                     if r.get("label") in POSITIVE_LABELS
                     and not recomputed_positive(r)]
    out["nearest_non_duplicate"] = meta.get("nearest_non_duplicate")
    out["nearest_duplicate"] = meta.get("nearest_duplicate")
    out["provenance"] = render_calibration_document(
        out, agreement=out["agreement"], n_fitting_set=out["n_fitting_set"],
        n_pairs=len(rows), grid=grid,
        nearest_non_duplicate=out["nearest_non_duplicate"],
        nearest_duplicate=out["nearest_duplicate"])
    out["meta"] = meta
    return out


def load_calibration(path: Path = CALIBRATION_PATH) -> dict:
    """The committed calibration, as the document the contract reads.

    Normalised on the way in (see `normalize_calibration_document`) so every
    reader — the run config, the nightly artifact and the tests — sees one shape,
    with `n_fitting_set`, `threshold_grid` and `provenance` derived from the rows
    rather than stored beside them.
    """
    return normalize_calibration_document(json.loads(Path(path).read_text()))


def calibration_agreement(path: Path = CALIBRATION_PATH):
    """The committed agreement string ("40/40"), or None if there is no set.

    Read by the run config so a nightly artifact says which calibration the
    threshold came from. None means the file is absent or unreadable, which must
    stay visible as "no calibration recorded" rather than being repaired into a
    number — see `_gold_slots_on_missing` for the same reasoning on missing gold.
    """
    try:
        return load_calibration(path).get("meta", {}).get("agreement_at_threshold")
    except (OSError, ValueError):
        return None


def disclosed_misses(rows: Sequence[dict]) -> list:
    """Rows the predicate cannot reach at ANY threshold, named rather than deleted.

    `in_fitting_set: false` marks a pair that is a real near-duplicate by reading
    and is invisible to a word-5-gram predicate anyway — the live case is
    `knowledge/ml/speculative-decoding-lora-adapter-interaction.md` versus
    `knowledge/ml/vllm-speculative-decoding-lora-interaction.md`: the same finding
    written twice about 200 words apart, one `vllm`-prefixed, scoring 0.2985.
    Keeping the row and naming it is the standing method in #1749, which disclosed
    its own false positives while excluding them from the threshold fit; deleting
    it would turn a known blind spot into a clean 100%, which is how #1751 read its
    whole 4/4 (and its whole 0/4) as evidence about a model.
    """
    # A labelled positive the predicate cannot reach, and nothing else. Not
    # `in_fitting_set is False`: an `unlabelled` row is outside the fitting set
    # too, and it is an abstention rather than a blind spot — calling the three
    # pairs no rule reached "duplicates we cannot see" would inflate the count of
    # known misses from 2 to 5 and make the number mean something else.
    return [r for r in rows
            if r.get("label") in POSITIVE_LABELS and not recomputed_positive(r)]


def agreement(rows: Sequence[dict], threshold: float,
              sim_fn=None) -> tuple:
    """(agree, total, disagreements) — the calibration's one honest number.

    `total` is the FITTING SET: every labelled pair except `disclosed_misses(rows)`,
    which are reported beside it and never quietly removed. A pair whose committed
    text is absent scores 0.0 rather than being skipped, so a stripped-down checkout
    shows up as disagreement instead of a quietly smaller denominator — the
    denominator shrinks only for a row the set itself declares unreachable, and
    that row is still counted in `n_pairs` and named in the report.
    """
    sim_fn = sim_fn or similarity
    # Two classes are out of the fit, both decided by the class of evidence and
    # never because a row disagreed:
    #   * `in_fitting_set: false` — a labelled duplicate the predicate cannot reach
    #     at any threshold (see `disclosed_misses`);
    #   * `label: "unlabelled"` — the reading rules found no subject tokens, no
    #     shared title family and no shared entity tag, so they abstained. An
    #     abstention has no predicted class to reproduce, and counting it as a
    #     correct `not-a-duplicate` is the zero-denominator defect wearing a
    #     positive: it would inflate agreement with rows that carry no opinion.
    # Both stay in the file and are counted in `n_pairs`.
    rows = [r for r in rows
            if r.get("in_fitting_set") is not False and r["label"] != "unlabelled"]
    agree, bad = 0, []
    for row in rows:
        texts = row.get("texts") or {}
        a = texts.get("a")
        b = texts.get("b")
        s = sim_fn(a or "", b or "")
        predicted = s >= threshold
        recorded = row["label"] in ("same", "near")
        if predicted == recorded:
            agree += 1
        else:
            bad.append({"pair_id": row["pair_id"], "jaccard": round(s, 4),
                        "label": row["label"], "path_a": row["path_a"],
                        "path_b": row["path_b"]})
    return agree, len(rows), bad


def calibration_report(path: Path = CALIBRATION_PATH) -> str:
    """The calibration recomputed from the committed texts, at the shipped
    threshold and at the grid the threshold could have been."""
    data = load_calibration(path)
    rows = data["pairs"]
    threshold = DUP_JACCARD_THRESHOLD
    agree, total, bad = agreement(rows, threshold)
    misses = disclosed_misses(rows)
    abstained = [r for r in rows if r["label"] == "unlabelled"]
    lines = [f"near-duplicate calibration: {Path(path).name}",
             f"threshold {threshold} (shingle k={SHINGLE_K}) — agreement "
             f"{agree}/{total} rows reproduced"
             + ("" if total else " — NO ROWS: denominator is zero, this is not a clean result")
             # The denominator's composition on the same line as the numerator: a
             # bare 35/35 over a 40-row file would be a number a reader cannot audit.
             + f" — fitting set {total} of {len(rows)} committed pairs "
             f"({len(misses)} disclosed miss(es) the predicate cannot reach at any "
             f"threshold: {', '.join(m['pair_id'] for m in misses) or 'none'}; "
             f"{len(abstained)} abstention(s) with no predicted class: "
             f"{', '.join(a['pair_id'] for a in abstained) or 'none'})"]
    if total:
        # brackets over the fitting set only: including a pair no threshold could
        # reach would report a margin the number does not have
        lo = [jaccard(shingles(content_body(r["texts"]["a"])),
                      shingles(content_body(r["texts"]["b"])))
              for r in rows
              if r.get("in_fitting_set") is not False
              and r["label"] not in ("same", "near")]
        hi = [jaccard(shingles(content_body(r["texts"]["a"])),
                      shingles(content_body(r["texts"]["b"])))
              for r in rows
              if r.get("in_fitting_set") is not False
              and r["label"] in ("same", "near")]
        lines.append(f"nearest non-duplicate {max(lo, default=float('-inf')):.4f} "
                     f"({len(lo)} rows) | nearest duplicate {min(hi, default=float('inf')):.4f} "
                     f"({len(hi)} rows) | margin below {threshold - max(lo, default=0):.4f}, "
                     f"above {min(hi, default=1) - threshold:.4f}")
    for b in bad:
        lines.append(f"  DISAGREE {b['pair_id']} {b['jaccard']:.4f} "
                     f"label={b['label']} {b['path_a']} || {b['path_b']}")
    lines.append("threshold grid (agreement at this value):")
    for t in (0.30, 0.40, 0.50, 0.55, 0.60, 0.65, 0.70, 0.75, 0.85):
        a2, t2, _ = agreement(rows, t)
        lines.append(f"  {t:.2f}: {a2}/{t2}")
    borderline = data.get("borderline_band") or {}
    if borderline:
        lines.append(f"human review owed on the borderline band "
                     f"{borderline.get('low')}-{borderline.get('high')}: "
                     f"{borderline.get('rows')}")
    return "\n".join(lines)


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(
        description="Report the near-duplicate predicate's calibration, or run "
                    "the corpus census.")
    ap.add_argument("--calibration", default=str(CALIBRATION_PATH),
                    help="calibration JSON to re-score (default: the committed one)")
    ap.add_argument("--census", action="store_true",
                    help="run the near-duplicate census over these roots and print JSON")
    ap.add_argument("--root", action="append", default=[],
                    help="root to census (repeatable; default: the vault)")
    ap.add_argument("--threshold", type=float, default=DUP_JACCARD_THRESHOLD,
                    help="census threshold (default: the calibrated one)")
    args = ap.parse_args(argv)
    if args.census:
        roots = [Path(r) for r in args.root] or [Path.home() / "obsidian"]
        print(json.dumps(census(roots, threshold=args.threshold), indent=2))
        return 0
    print(calibration_report(Path(args.calibration)))
    return 0


if __name__ == "__main__":
    sys.exit(main())
